"""Evaluate HMR2a using the official PoseTrack18 NPZ, ImageDataset and PCK.

Versioned copy of evaluate_hmr2a_full_posetrack18_v1.py; the original is unchanged.
No downloads, extra filtering, mapping, crop scale, normalization or aggregation
are introduced. Supply released evaluation metadata or an NPZ generated by the
unmodified official posetrack_to_npz.py. All outputs are created exclusively.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import sys
import time
import traceback
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

HMR2A_SHA256 = "2dcf79638109781d1ae5f5c44fee5f55bc83291c210653feead9b7f04fa6f20e"
BODY12_HMR_INDICES = (5, 2, 6, 3, 7, 4, 12, 9, 13, 10, 14, 11)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("source-root", "checkpoint", "model-config", "hmr-data-root",
                 "dataset-npz", "image-root", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument("--log-frequency", type=int, default=50)
    parser.add_argument("--smoke-samples", type=int, default=0,
                        help="First N NPZ entries for a smoke run; 0 evaluates all entries")
    args = parser.parse_args(argv)
    if args.batch_size <= 0 or args.num_workers < 0 or args.log_frequency <= 0:
        parser.error("batch-size/log-frequency must be positive; num-workers nonnegative")
    if args.smoke_samples < 0:
        parser.error("smoke-samples must be nonnegative")
    for name in ("source_root", "checkpoint", "model_config", "hmr_data_root",
                 "dataset_npz", "image_root", "output"):
        setattr(args, name, getattr(args, name).expanduser().resolve())
    return args


def write_result_exclusive(output: Path, result: dict[str, Any]) -> None:
    with output.open("x", encoding="utf-8") as stream:
        json.dump(result, stream, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write("\n")


def run_official(args: argparse.Namespace, result: dict[str, Any]) -> None:
    import numpy as np
    import torch
    from torch.utils.data import DataLoader, Subset

    required_files = (args.checkpoint, args.model_config, args.dataset_npz,
                      args.hmr_data_root / "SMPL_to_J19.pkl",
                      args.hmr_data_root / "smpl_mean_params.npz")
    required_dirs = (args.source_root, args.image_root, args.hmr_data_root / "smpl")
    for path in required_files:
        if not path.is_file():
            raise FileNotFoundError(f"Required existing file not found: {path}")
    for path in required_dirs:
        if not path.is_dir():
            raise FileNotFoundError(f"Required existing directory not found: {path}")
    for label, path in (("checkpoint", args.checkpoint), ("dataset_npz", args.dataset_npz),
                        ("model_config", args.model_config),
                        ("joint_regressor_extra", args.hmr_data_root / "SMPL_to_J19.pkl"),
                        ("smpl_mean_params", args.hmr_data_root / "smpl_mean_params.npz")):
        result["hashes"][label] = sha256_file(path)
    if result["hashes"]["checkpoint"] != HMR2A_SHA256:
        raise ValueError("Checkpoint is not the explicitly verified HMR2.0a: "
                         + result["hashes"]["checkpoint"])
    result["checkpoint_identity_verified"] = True

    # Avoid download_models/load_hmr2; use only the supplied local resources.
    source_text = str(args.source_root)
    if source_text not in sys.path:
        sys.path.insert(0, source_text)
    from hmr2.configs import get_config
    from hmr2.datasets.image_dataset import ImageDataset
    from hmr2.models import HMR2
    from hmr2.utils import Evaluator, recursive_to

    source_files = ("eval.py", "hmr2/configs/__init__.py", "hmr2/models/__init__.py",
                    "hmr2/models/hmr2.py", "hmr2/models/smpl_wrapper.py",
                    "hmr2/datasets/image_dataset.py", "hmr2/datasets/utils.py",
                    "hmr2/datasets/preprocess/posetrack_to_npz.py",
                    "hmr2/utils/pose_utils.py", "hmr2/utils/pck_accuracy.py")
    result["official_source_sha256"] = {
        name: sha256_file(args.source_root / name) for name in source_files
        if (args.source_root / name).is_file()
    }
    cfg = get_config(str(args.model_config), update_cachedir=False)
    cfg.defrost()
    # Exact fallback in official load_hmr2; keep an existing BBOX_SHAPE.
    if cfg.MODEL.BACKBONE.TYPE == "vit" and "BBOX_SHAPE" not in cfg.MODEL:
        if cfg.MODEL.IMAGE_SIZE != 256:
            raise ValueError("Official ViT BBOX_SHAPE fallback requires IMAGE_SIZE=256")
        cfg.MODEL.BBOX_SHAPE = [192, 256]
    cfg.SMPL.MODEL_PATH = str(args.hmr_data_root / "smpl")
    cfg.SMPL.JOINT_REGRESSOR_EXTRA = str(args.hmr_data_root / "SMPL_to_J19.pkl")
    cfg.SMPL.MEAN_PARAMS = str(args.hmr_data_root / "smpl_mean_params.npz")
    cfg.freeze()
    result["model_configuration"] = {
        "image_size": int(cfg.MODEL.IMAGE_SIZE),
        "bbox_shape": list(cfg.MODEL.BBOX_SHAPE) if "BBOX_SHAPE" in cfg.MODEL else None,
        "focal_length": float(cfg.EXTRA.FOCAL_LENGTH),
        "pelvis_ind": int(cfg.EXTRA.PELVIS_IND),
        "smpl_update_hips": bool(cfg.SMPL.get("UPDATE_HIPS", False)),
        "get_config_update_cachedir": False,
    }
    dataset = ImageDataset(cfg, str(args.dataset_npz), str(args.image_root), train=False)
    total = len(dataset)
    if not total:
        raise RuntimeError("Official PoseTrack NPZ contains no person entries")
    if dataset.keypoints_2d.shape != (total, 44, 3):
        raise ValueError(f"Expected official 44-point targets; got {dataset.keypoints_2d.shape}")
    if not np.isfinite(dataset.keypoints_2d).all():
        raise ValueError("Non-finite GT keypoints in NPZ")
    if not np.isfinite(dataset.scale).all() or not (dataset.scale > 0).all():
        raise ValueError("NPZ contains invalid crop scales")
    selected_count = min(args.smoke_samples, total) if args.smoke_samples else total
    selected = Subset(dataset, range(selected_count)) if args.smoke_samples else dataset
    expected_counts = (dataset.keypoints_2d[:selected_count, :, 2] > 0.5).sum(0)
    full_counts = (dataset.keypoints_2d[:, :, 2] > 0.5).sum(0)
    result["coverage"] = {
        "npz_person_entries": total, "planned_person_entries": selected_count,
        "processed_person_entries": 0, "unique_npz_indices": 0,
        "selected_gt_counts_44": expected_counts.tolist(),
        "full_npz_gt_counts_44": full_counts.tolist(),
        "processed_gt_counts_44": [0] * 44,
        "full_npz_all_body12_annotated_count": int(
            (dataset.keypoints_2d[:, BODY12_HMR_INDICES, 2] > 0.5).all(1).sum()),
        "selected_gt_keypoints": int(expected_counts.sum()),
        "full_npz_gt_keypoints": int(full_counts.sum()),
        "complete_planned_subset": False, "complete_full_npz": False,
    }
    # Preflight missing input before allocating the model; never silently drop it.
    for idx in range(selected_count):
        image_name = dataset.imgname[idx]
        if isinstance(image_name, bytes):
            image_name = image_name.decode("utf-8")
        if not (args.image_root / str(image_name)).is_file():
            raise FileNotFoundError(f"NPZ entry {idx}: image missing: {image_name}")

    device = torch.device(args.device)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA requested but unavailable; no implicit CPU fallback")
    model = HMR2.load_from_checkpoint(str(args.checkpoint), strict=True, cfg=cfg,
                                    map_location="cpu", init_renderer=False).eval()
    model.requires_grad_(False)
    model = model.to(device)
    loader = DataLoader(selected, batch_size=args.batch_size, shuffle=False,
                        num_workers=args.num_workers, pin_memory=device.type == "cuda",
                        persistent_workers=args.num_workers > 0, drop_last=False)
    # Official POSETRACK-VAL dummy 3D keypoint list and mode_kpl2; the Evaluator
    # delegates PCK to the unchanged official EvaluatorPCK implementation.
    evaluator = Evaluator(dataset_length=selected_count, keypoint_list=[0],
                          pelvis_ind=cfg.EXTRA.PELVIS_IND, metrics=["mode_kpl2"],
                          pck_thresholds=[0.05, 0.1])
    seen: set[int] = set()
    processed_counts = np.zeros(44, dtype=np.int64)
    crop_examples: list[dict[str, Any]] = []
    inference_started = time.monotonic()
    with torch.no_grad():
        for batch_index, batch in enumerate(loader):
            indices = [int(value) for value in batch["idx"].tolist()]
            if len(indices) != len(set(indices)) or any(idx in seen for idx in indices):
                raise RuntimeError("Repeated NPZ person index during evaluation")
            if any(not 0 <= idx < selected_count for idx in indices):
                raise RuntimeError("NPZ index outside selected evaluation subset")
            batch = recursive_to(batch, device)
            output = model(batch)
            prediction = output["pred_keypoints_2d"]
            if prediction.shape != batch["keypoints_2d"][..., :2].shape:
                raise RuntimeError("Predicted/GT arrays do not have the same 44-point shape")
            if not bool(torch.isfinite(prediction).all()):
                raise RuntimeError("Model produced non-finite real SMPL projections")
            evaluator(output, batch)
            seen.update(indices)
            processed_counts += (batch["keypoints_2d"][..., 2] > 0.5).sum(0).cpu().numpy()
            coverage = result["coverage"]
            coverage["processed_person_entries"] = len(seen)
            coverage["unique_npz_indices"] = len(seen)
            coverage["processed_gt_counts_44"] = processed_counts.tolist()
            for offset, idx in enumerate(indices):
                if len(crop_examples) >= 3 and idx != selected_count - 1:
                    continue
                crop_examples.append({
                    "npz_idx": idx, "image": str(batch["imgname_rel"][offset]),
                    "box_center": batch["box_center"][offset].detach().cpu().tolist(),
                    "box_size": float(batch["box_size"][offset].item()),
                    "scale_times_200": (batch["_scale"][offset] * 200).detach().cpu().tolist(),
                })
            if (batch_index + 1) % args.log_frequency == 0 or len(seen) == selected_count:
                print(json.dumps({"event": "progress", "processed": len(seen),
                                  "planned": selected_count, "npz_total": total,
                                  "seconds": time.monotonic() - inference_started}), flush=True)
    if seen != set(range(selected_count)) or evaluator.counter != selected_count:
        raise RuntimeError("Incomplete person coverage: cannot report success")
    if evaluator.pck_evaluator.counter != selected_count:
        raise RuntimeError("Official PCK evaluator person coverage mismatch")
    if not np.array_equal(processed_counts, expected_counts):
        raise RuntimeError("Processed per-joint GT counts differ from the selected NPZ")
    metrics = {key: float(value) for key, value in evaluator.get_metrics_dict().items()}
    if any(not math.isfinite(value) for value in metrics.values()):
        raise RuntimeError("Non-finite official metrics: cannot report success")
    result["metrics"] = metrics
    result["primary_metrics"] = {
        "PCKn@0.05_macro": metrics["kpAvg_pck_0.05"],
        "PCKn@0.10_macro": metrics["kpAvg_pck_0.1"],
    }
    result["per_joint_44"] = [{
        "hmr_index": idx, "gt_count": int(processed_counts[idx]),
        "PCKn@0.05": metrics.get(f"kp{idx}_pck_0.05"),
        "PCKn@0.10": metrics.get(f"kp{idx}_pck_0.1"),
    } for idx in range(44)]
    result["active_joint_count"] = int((processed_counts > 0).sum())
    result["crop_examples"] = crop_examples
    result["coverage"]["complete_planned_subset"] = True
    result["coverage"]["complete_full_npz"] = not bool(args.smoke_samples)
    result["inference_seconds"] = time.monotonic() - inference_started
    result["status"] = ("HMR2A_OFFICIAL_POSETRACK18_SMOKE_OK" if args.smoke_samples
                         else "HMR2A_OFFICIAL_POSETRACK18_FULL_OK")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.output.exists():
        raise FileExistsError(f"Refusing to replace existing output: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Independent exclusive marker prevents duplicate inference for the same run.
    marker = args.output.with_name(args.output.name + ".started.json")
    with marker.open("x", encoding="utf-8") as stream:
        json.dump({"pid": os.getpid(), "output": str(args.output),
                   "started_utc": datetime.now(timezone.utc).isoformat()}, stream)
    started = time.monotonic()
    result: dict[str, Any] = {
        "status": "HMR2A_OFFICIAL_POSETRACK18_FAILED",
        "split": "PoseTrack18 val development", "primary": "real SMPL projection",
        "protocol": "official HMR2 ImageDataset + Evaluator/EvaluatorPCK, unchanged",
        "scope": "smoke subset" if args.smoke_samples else "complete official NPZ",
        "model": "HMR2.0a", "checkpoint_identity_verified": False,
        "expected_checkpoint_sha256": HMR2A_SHA256,
        "hashes": {"evaluator_code": sha256_file(Path(__file__))},
        "copied_from": "evaluate_hmr2a_full_posetrack18_v1.py",
        "arguments": {name: str(value) if isinstance(value, Path) else value
                      for name, value in vars(args).items()},
        "precision": "FP32, no autocast", "test_used_for_model_selection": False,
        "official_poseval_ap_or_tracking": False, "ram_protocol_equality_claimed": False,
        "started_utc": datetime.now(timezone.utc).isoformat(),
    }
    exit_code = 0
    try:
        run_official(args, result)
    except (Exception, KeyboardInterrupt) as exc:
        result["status"] = "HMR2A_OFFICIAL_POSETRACK18_FAILED"
        result["exception"] = {"type": type(exc).__name__, "message": str(exc),
                               "traceback": traceback.format_exc()}
        for key in ("primary_metrics", "metrics", "per_joint_44"):
            result.pop(key, None)
        exit_code = 130 if isinstance(exc, KeyboardInterrupt) else 1
        print(result["exception"]["traceback"], file=sys.stderr, flush=True)
    result["elapsed_seconds"] = time.monotonic() - started
    result["finished_utc"] = datetime.now(timezone.utc).isoformat()
    write_result_exclusive(args.output, result)
    print(json.dumps({"status": result["status"], "output": str(args.output),
                      "primary_metrics": result.get("primary_metrics"),
                      "coverage": result.get("coverage")}, allow_nan=False), flush=True)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
